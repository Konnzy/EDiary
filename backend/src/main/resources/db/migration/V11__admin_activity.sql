CREATE TABLE admin_activity (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_actor_login VARCHAR(100) NOT NULL,
    activity_title VARCHAR(100) NOT NULL,
    activity_target VARCHAR(255) NOT NULL,
    activity_occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_admin_activity_occurred_at ON admin_activity (activity_occurred_at DESC, activity_id DESC);
